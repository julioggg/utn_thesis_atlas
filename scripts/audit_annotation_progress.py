#!/usr/bin/env python3
"""Audit restricted independent SDG/PDOT coder worksheets without exporting rows.

Expected private files were generated by prepare_blinded_validation_sample.py.
This script ONLY writes aggregate integrity/progress statistics. No student
handles, study IDs, thesis texts, coder notes or individual labels are exported.

This is a quality gate, not a substitute for human annotation or adjudication.
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


SDG = {f"ODS {n}" for n in range(1, 18)}
PDOT = {f"PDOT {n}" for n in range(1, 7)}
YES = {"1", "true", "yes", "y", "si", "sí"}
NO = {"", "0", "false", "no", "n"}
ANNOTATION_COLUMNS = {
    "study_id", "private_source_handle",
    "sdg_primary", "sdg_secondary", "sdg_no_match",
    "pdot_primary", "pdot_secondary", "pdot_no_match",
    "uncertain", "brief_evidence", "coder_notes",
}
FORBIDDEN_CODER_COLUMNS = {
    "ods_top1", "ods_top1_score", "ods_top2_score",
    "pdot_top1", "pdot_top1_score", "pdot_top2_score",
    "selection_stratum", "faculty", "source_row_index",
}


def normalize_text(value):
    import pandas as pd
    if pd.isna(value):
        return ""
    return str(value).strip()


def norm_flag(value):
    text = normalize_text(value).lower()
    if text in YES:
        return True
    if text in NO:
        return False
    raise ValueError("Invalid no-match flag. Use 'yes' or 'no'.")


def evaluate_domain(row, prefix, allowed):
    """Return incomplete, complete or invalid; privacy-safe reason labels."""
    primary = normalize_text(row[f"{prefix}_primary"]).upper()
    secondary = normalize_text(row[f"{prefix}_secondary"]).upper()
    flag_value = row[f"{prefix}_no_match"]
    try:
        no_match = norm_flag(flag_value)
    except ValueError:
        return "invalid", "invalid_flag"
    if not primary and not secondary and not no_match:
        return "incomplete", None
    if no_match:
        if primary or secondary:
            return "invalid", "no_match_conflict"
        return "complete", None
    if not primary:
        return "invalid", "secondary_without_primary"
    if primary not in allowed:
        return "invalid", "invalid_primary_code"
    if secondary and secondary not in allowed:
        return "invalid", "invalid_secondary_code"
    if secondary == primary:
        return "invalid", "secondary_equals_primary"
    return "complete", None


def inspect_sheet(sheet, expected_ids, expected_handles):
    """Inspect file integrity and aggregate annotation progress."""
    cols = set(sheet.columns)
    if missing := ANNOTATION_COLUMNS - cols:
        raise ValueError("Coder sheet is missing required fields: " + ", ".join(sorted(missing)))
    if cols & FORBIDDEN_CODER_COLUMNS:
        raise ValueError("Coder sheet includes prediction/sampling fields, breaking blinding")
    ids = sheet["study_id"].map(normalize_text)
    if ids.duplicated().any() or len(ids) != len(expected_ids) or set(ids) != expected_ids:
        raise ValueError("Coder sheet ID set does not match frozen validation sample")
    handles = sheet["private_source_handle"].map(normalize_text)
    # Quoted CSV formula prefixes are escaped when the private sheets are created.
    canonical_handles = handles.map(lambda h: h[1:] if h.startswith("'") else h)
    if any(expected_handles[id_] != h for id_, h in zip(ids, canonical_handles)):
        raise ValueError("Coder source handles do not match frozen sample")
    status = Counter()
    domain_status = Counter()
    problems = Counter()
    completed_ids = set()
    for _, row in sheet.iterrows():
        sdg_status, sdg_problem = evaluate_domain(row, "sdg", SDG)
        pdot_status, pdot_problem = evaluate_domain(row, "pdot", PDOT)
        domain_status["sdg_" + sdg_status] += 1
        domain_status["pdot_" + pdot_status] += 1
        if sdg_problem:
            problems["sdg_" + sdg_problem] += 1
        if pdot_problem:
            problems["pdot_" + pdot_problem] += 1
        uncertain_text = normalize_text(row["uncertain"]).lower()
        if uncertain_text not in YES | NO:
            problems["invalid_uncertain_flag"] += 1
        valid = sdg_status == "complete" and pdot_status == "complete"
        evidence = bool(normalize_text(row["brief_evidence"]))
        if valid and not evidence:
            problems["complete_without_evidence"] += 1
        if valid and evidence and uncertain_text in YES | NO:
            status["complete"] += 1
            completed_ids.add(normalize_text(row["study_id"]))
        elif sdg_status == "invalid" or pdot_status == "invalid":
            status["invalid"] += 1
        elif all(not normalize_text(row[key]) for key in ANNOTATION_COLUMNS
                 if key not in {"study_id", "private_source_handle"}):
            status["not_started"] += 1
        else:
            status["in_progress"] += 1
    return {
        "rows": len(sheet),
        "complete": status["complete"],
        "not_started": status["not_started"],
        "in_progress": status["in_progress"],
        "invalid": status["invalid"],
        "domain_counts": dict(sorted(domain_status.items())),
        "validation_issues": dict(sorted(problems.items())),
    }, completed_ids


def inspect_files(private_dir):
    import pandas as pd
    master = pd.read_csv(private_dir / "sample_master_private.csv", dtype=str,
                         keep_default_na=False)
    if "study_id" not in master or "handle_id" not in master:
        raise ValueError("Private sample master is missing ID or handle")
    ids = master["study_id"].map(normalize_text)
    handles = master["handle_id"].map(normalize_text)
    if ids.duplicated().any() or handles.duplicated().any() or not all(ids) or not all(handles):
        raise ValueError("Private master has empty/duplicate source or study IDs")
    expected = dict(zip(ids, handles))
    summaries, finished = {}, []
    for letter in ("A", "B"):
        sheet = pd.read_csv(private_dir / f"coder_{letter}_private.csv", dtype=str,
                            keep_default_na=False)
        summary, completed = inspect_sheet(sheet, set(expected), expected)
        summaries[letter] = summary
        finished.append(completed)
    common = len(finished[0] & finished[1])
    return {
        "schema_version": 1,
        "status": "annotation_progress_only",
        "selected_theses": len(expected),
        "coder_sheet_integrity": "passed",
        "coder_progress": summaries,
        "both_coders_complete": common,
        "all_annotations_finished": common == len(expected),
        "model_validation_or_intercoder_agreement_computed": False,
        "notes": [
            "Rows are counted complete only after both domains and evidence fields are filled.",
            "Blank no-match flags are treated as 'no'; use 'yes' only for an explicit no-match judgment.",
            "Codes must be 'ODS 1' through 'ODS 17' and 'PDOT 1' through 'PDOT 6'.",
            "This report does not contain individual annotations, identifiers or textual evidence.",
            "Do not calculate model precision or Cohen's kappa before both independent coding sheets are frozen.",
        ],
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--private-dir", type=Path,
                   default=Path("data/revision_private/validation"))
    p.add_argument("--output", type=Path,
                   default=Path("docs/audits/annotation_progress.json"))
    a = p.parse_args()
    workspace = Path(__file__).resolve().parent.parent
    private = a.private_dir.expanduser().resolve()
    if not private.is_relative_to(workspace / "data"):
        raise ValueError("Input sheets must be in the private git-ignored data/ directory")
    report = inspect_files(private)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
    print(f"Integrity OK: {report['selected_theses']} unique theses.")
    for name, d in report["coder_progress"].items():
        print(f"Coder {name}: {d['complete']} complete, {d['not_started']} not started, "
              f"{d['in_progress']} in progress, {d['invalid']} invalid.")
    print("No individual record or annotations exported.")


if __name__ == "__main__":
    main()
